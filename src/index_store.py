import numpy as np
import json
import re
import shutil
import uuid
from pathlib import Path

import faiss

from src.retriever import SemanticRetriever


SCHEMA_VERSION = 1
DEFAULT_STORAGE_DIR = Path(__file__).resolve().parent.parent / "storage" / "document_index"


def save_retriever(
    retriever: SemanticRetriever,
    storage_dir: str | Path = DEFAULT_STORAGE_DIR,
) -> None:
    """Save the FAISS index and chunk metadata as a new snapshot."""
    if retriever.index is None or not retriever.chunks:
        raise ValueError("Cannot save an empty retriever.")

    storage_dir = Path(storage_dir)
    snapshots_dir = storage_dir / "snapshots"
    snapshots_dir.mkdir(parents=True, exist_ok=True)

    snapshot_id = uuid.uuid4().hex
    temporary_dir = snapshots_dir / f".tmp-{snapshot_id}"
    snapshot_dir = snapshots_dir / snapshot_id
    temporary_dir.mkdir()

    try:
        faiss.write_index(
            retriever.index,
            str(temporary_dir / "index.faiss"),
        )

        with (temporary_dir / "chunks.json").open(
            "w", encoding="utf-8"
        ) as file:
            json.dump(
                retriever.chunks,
                file,
                ensure_ascii=False,
                indent=2,
            )

        manifest = {
            "schema_version": SCHEMA_VERSION,
            "snapshot_id": snapshot_id,
            "model_name": retriever.model_name,
            "chunk_count": len(retriever.chunks),
            "vector_count": retriever.index.ntotal,
            "embedding_dimension": retriever.index.d,
        }

        with (temporary_dir / "manifest.json").open(
            "w", encoding="utf-8"
        ) as file:
            json.dump(manifest, file, indent=2)

        # Publish a complete snapshot before updating the pointer.
        temporary_dir.rename(snapshot_dir)

        pointer_tmp = storage_dir / f".current-{snapshot_id}.tmp"
        pointer = storage_dir / "current.json"

        with pointer_tmp.open("w", encoding="utf-8") as file:
            json.dump({"snapshot_id": snapshot_id}, file)

        # Replacing this small pointer makes the new snapshot active.
        pointer_tmp.replace(pointer)

    finally:
        if temporary_dir.exists():
            shutil.rmtree(temporary_dir, ignore_errors=True)


def load_retriever(
    storage_dir: str | Path = DEFAULT_STORAGE_DIR,
) -> SemanticRetriever | None:
    """Load the most recently published snapshot, if one exists."""
    storage_dir = Path(storage_dir)
    pointer = storage_dir / "current.json"

    if not pointer.exists():
        return None

    with pointer.open("r", encoding="utf-8") as file:
        pointer_data = json.load(file)

    snapshot_id = pointer_data.get("snapshot_id", "")

    # Only accept IDs generated by this module.
    if not isinstance(snapshot_id, str) or not re.fullmatch(
        r"[a-f0-9]{32}", snapshot_id
    ):
        raise ValueError("Invalid saved-index snapshot identifier.")

    snapshot_dir = storage_dir / "snapshots" / snapshot_id
    manifest_path = snapshot_dir / "manifest.json"
    chunks_path = snapshot_dir / "chunks.json"
    index_path = snapshot_dir / "index.faiss"

    if not all(
        path.is_file()
        for path in (manifest_path, chunks_path, index_path)
    ):
        raise ValueError("Saved index is incomplete or missing files.")

    with manifest_path.open("r", encoding="utf-8") as file:
        manifest = json.load(file)

    if manifest.get("schema_version") != SCHEMA_VERSION:
        raise ValueError("Unsupported saved-index schema version.")

    if manifest.get("snapshot_id") != snapshot_id:
        raise ValueError("Saved-index snapshot metadata does not match.")

    with chunks_path.open("r", encoding="utf-8") as file:
        chunks = json.load(file)

    if not isinstance(chunks, list) or not chunks:
        raise ValueError("Saved index contains no valid chunks.")

    # FAISS index files should only be loaded from trusted local storage.
    index = faiss.read_index(str(index_path))

    if index.ntotal != len(chunks):
        raise ValueError("Saved index and chunk metadata do not match.")

    if index.ntotal != manifest.get("vector_count"):
        raise ValueError("Saved vector count does not match the manifest.")

    if index.d != manifest.get("embedding_dimension"):
        raise ValueError("Saved embedding dimensions do not match.")

    retriever = SemanticRetriever(
        model_name=manifest["model_name"]
    )
    retriever.index = index
    retriever.chunks = chunks

    return retriever


def delete_saved_index(
    storage_dir: str | Path = DEFAULT_STORAGE_DIR,
) -> None:
    """Delete the application's saved index, not the original PDFs."""
    storage_dir = Path(storage_dir)

    if storage_dir.exists():
        shutil.rmtree(storage_dir)


def delete_document(
    retriever: SemanticRetriever,
    document_id: str,
    storage_dir: str | Path = DEFAULT_STORAGE_DIR,
) -> SemanticRetriever | None:
    """Delete one document and persist the remaining searchable collection."""
    if retriever.index is None or not retriever.chunks:
        raise ValueError("There are no indexed documents to delete.")

    if not document_id:
        raise ValueError("A document ID is required.")

    keep_positions = [
        i
        for i, chunk in enumerate(retriever.chunks)
        if chunk.get("document_id") != document_id
    ]

    if len(keep_positions) == len(retriever.chunks):
        raise ValueError("The requested document was not found.")

    # If this was the last document, remove the saved collection.
    if not keep_positions:
        delete_saved_index(storage_dir)
        return None

    remaining_chunks = [
        retriever.chunks[i] for i in keep_positions
    ]

    # Preserve the vectors for all documents that remain.
    remaining_vectors = np.vstack([
        retriever.index.reconstruct(i)
        for i in keep_positions
    ]).astype("float32")

    updated = SemanticRetriever(model_name=retriever.model_name)
    updated.index = faiss.IndexFlatIP(retriever.index.d)
    updated.index.add(remaining_vectors)
    updated.chunks = remaining_chunks

    # Persist first; the app should update its state only after this succeeds.
    save_retriever(updated, storage_dir)
    return updated
